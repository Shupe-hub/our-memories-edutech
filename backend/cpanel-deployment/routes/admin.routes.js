import { Router } from 'express';
import { authenticate, rateLimit, requireAdmin, requirePasswordChanged, requireSuperAdmin, sameOrigin } from '../middleware/authenticate.js';
import { activity, adminDashboard, changePassword, createAdmin, dashboard, deleteAdmin, getAdmin, listAdmins, listStudents, profile, resendInvitation, sendEmailTest, setAdminStatus, updateAdmin } from '../controllers/admin.controller.js';
import { addEnquiryNote, assignEnquiry, downloadAdminDocument, enquiryStats, getAdminEnquiry, listAdminDocuments, listAdminEnquiries, listAssignees, updateAdminDocumentStatus, updateEnquiryFeedback, updateEnquiryStatus } from '../controllers/application.controller.js';
import { adminCatalogue, listAdminWorkflowApplications, saveCatalogue, updateAdminApplicationFee, updateAdminWorkflowApplication, updateWorkflowDocumentStatus } from '../controllers/education-workflow.controller.js';
const router=Router();
router.use(authenticate);
router.use(sameOrigin);
router.use((req,res,next)=>req.method==='GET'?next():rateLimit({windowMs:60*60*1000,max:20})(req,res,next));
router.get('/system-admin/dashboard',requireSuperAdmin,dashboard);
router.post('/system-admin/email/test',requireSuperAdmin,requirePasswordChanged,sendEmailTest);
router.get('/system-admin/administrators',requireSuperAdmin,listAdmins);
router.post('/system-admin/administrators',requireSuperAdmin,createAdmin);
router.get('/system-admin/administrators/:id',requireSuperAdmin,getAdmin);
router.patch('/system-admin/administrators/:id',requireSuperAdmin,updateAdmin);
router.patch('/system-admin/administrators/:id/status',requireSuperAdmin,setAdminStatus);
router.post('/system-admin/administrators/:id/resend-invitation',requireSuperAdmin,resendInvitation);
router.delete('/system-admin/administrators/:id',requireSuperAdmin,deleteAdmin);
router.get('/system-admin/activity',requireSuperAdmin,activity);
router.get('/admin/dashboard',requireAdmin,requirePasswordChanged,adminDashboard);
router.get('/admin/students',requireAdmin,requirePasswordChanged,listStudents);
router.get('/admin/profile',requireAdmin,requirePasswordChanged,profile);
router.get('/admin/applications/stats',requireAdmin,requirePasswordChanged,enquiryStats);
router.get('/admin/applications/assignees',requireAdmin,requirePasswordChanged,listAssignees);
router.get('/admin/applications',requireAdmin,requirePasswordChanged,listAdminEnquiries);
router.get('/admin/applications/:id',requireAdmin,requirePasswordChanged,getAdminEnquiry);
router.patch('/admin/applications/:id/status',requireAdmin,requirePasswordChanged,updateEnquiryStatus);
router.patch('/admin/applications/:id/feedback',requireAdmin,requirePasswordChanged,updateEnquiryFeedback);
router.post('/admin/applications/:id/notes',requireAdmin,requirePasswordChanged,addEnquiryNote);
router.patch('/admin/applications/:id/assign',requireAdmin,requirePasswordChanged,assignEnquiry);
router.get('/admin/applications/:id/documents',requireAdmin,requirePasswordChanged,listAdminDocuments);
router.patch('/admin/applications/:id/documents/:documentId/status',requireAdmin,requirePasswordChanged,updateAdminDocumentStatus);
router.get('/admin/applications/:id/documents/:documentId/download',requireAdmin,requirePasswordChanged,downloadAdminDocument);
router.get('/admin/education/applications',requireAdmin,requirePasswordChanged,listAdminWorkflowApplications);
router.patch('/admin/education/applications/:kind/:id',requireAdmin,requirePasswordChanged,updateAdminWorkflowApplication);
router.patch('/admin/education/applications/university/:id/fee',requireAdmin,requirePasswordChanged,updateAdminApplicationFee);
router.patch('/admin/education/applications/:kind/:id/documents/:documentId/status',requireAdmin,requirePasswordChanged,updateWorkflowDocumentStatus);
router.get('/admin/education/catalogue',requireAdmin,requirePasswordChanged,adminCatalogue);
router.post('/admin/education/catalogue/:entity',requireAdmin,requirePasswordChanged,saveCatalogue);
router.patch('/admin/education/catalogue/:entity/:id',requireAdmin,requirePasswordChanged,saveCatalogue);
router.post('/admin/change-password',requireAdmin,changePassword);
export default router;
